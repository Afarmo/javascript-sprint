const mathObj = {
  abs(value) {
    return Math.abs(value);
  },

  isEven(value) {
    return Math.isEven(value);
  },

  isOdd(value) {
    return Math.isOdd(value);
  },
  isStrictlyPositive(value) {
    return Math.isStrictlyPostive(value);
  },

  min(a, b) {
    return Math.min(a, b);
  },

  max(a, b) {
    return Math.max(a, b);
  },
};
